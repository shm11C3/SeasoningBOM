import { describe, expect, it } from "vitest";
import {
  fixedNow,
  makeComponent,
  makeInventoryItem,
  makeRecipe,
  makeSettings,
} from "../../test/factories/domainFactories";
import { runNomAudit } from "../audit/runNomAudit";
import { generateSeasoningBOM } from "./generateSeasoningBOM";

describe("generateSeasoningBOM", () => {
  it("generates a SeasoningBOM snapshot with public recipe alerts only", () => {
    const recipe = makeRecipe();
    const components = [
      makeComponent({
        transitiveDependencies: [
          { name: "wheat", dependencyType: "transitive", allergens: ["wheat"] },
        ],
      }),
    ];
    const inventoryItems = [makeInventoryItem({ bestBeforeDate: "2026-07-04" })];
    const settings = makeSettings();
    const audit = runNomAudit({ recipe, components, inventoryItems, now: fixedNow, settings });

    const bom = generateSeasoningBOM({
      recipe,
      components,
      recipeAlerts: audit.recipeAlerts,
      generatedAt: fixedNow,
    });

    expect(bom).toMatchObject({
      bomFormat: "SeasoningBOM",
      specVersion: "0.1.0",
      repository: {
        owner: "me",
        name: "curry-rice",
        version: "1.2.0",
        visibility: "public",
      },
      components: [
        expect.objectContaining({
          name: "rice",
          dependencies: [expect.objectContaining({ name: "wheat" })],
        }),
      ],
      audit: expect.objectContaining({
        issues: [expect.objectContaining({ category: "transitive-dependency" })],
      }),
    });
    expect("lifecycle" in bom.components[0]).toBe(false);
    expect(JSON.stringify(bom)).not.toContain('"category":"eol"');
  });

  it("does not include private inventory audit details even when generated by an owner", () => {
    const recipe = makeRecipe();
    const component = makeComponent({ ingredientName: "soy sauce" });
    const settings = makeSettings();
    const audit = runNomAudit({
      recipe,
      components: [component],
      inventoryItems: [],
      now: fixedNow,
      settings,
    });

    const bom = generateSeasoningBOM({
      recipe,
      components: [component],
      recipeAlerts: audit.recipeAlerts,
      generatedAt: fixedNow,
    });

    expect(bom.components[0]).not.toHaveProperty("lifecycle");
    expect(bom.audit.issues).toEqual([]);
  });
});
